      <p>Hari Santri bukan perayaan perang. Ia menjadi pengingat bahwa ulama dan santri pernah mengambil tanggung jawab besar ketika kemerdekaan terancam. Semangat itu kini diwujudkan melalui pendidikan, pengabdian, persatuan, serta kerja nyata untuk membangun bangsa.</p>


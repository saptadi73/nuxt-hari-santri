      <h2>Fatwa Jihad menyebar dari masjid ke masjid</h2>
      <p>Bersamaan dengan resolusi yang ditujukan kepada pemerintah, PBNU menyebarkan Fatwa Jihad kepada umat. Fatwa itu menempatkan kewajiban langsung bagi umat Islam yang berada dekat dengan kedudukan musuh, sementara masyarakat di wilayah yang lebih jauh tetap memiliki tanggung jawab kolektif.</p>
      <p>Seruan tersebut tidak terutama disebarkan melalui koran atau radio. Ia bergerak dari surau ke surau, masjid ke masjid, pesantren ke pesantren, dan dari mulut para kiai kepada santri serta masyarakat.</p>

      <h2>Santri turun mempertahankan Republik</h2>
      <p>Ribuan santri bergabung dengan laskar Hizbullah dan Sabilillah. Mereka tidak hanya memberikan dukungan moral dan doa, tetapi ikut menjaga kota serta bertempur menghadapi Sekutu dan NICA. Banyak di antara mereka gugur dalam perjuangan.</p>
      <p>Tiga hari setelah resolusi, pasukan Inggris di bawah Brigadir A.W.S. Mallaby mendarat di Surabaya. Bentrokan pecah pada akhir Oktober, kemudian berkembang menjadi pertempuran besar pada 10 November 1945. Resolusi Jihad menjadi salah satu sumber semangat yang menggerakkan perlawanan rakyat.</p>


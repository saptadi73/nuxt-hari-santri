      <p>Resolusi tersebut menegaskan bahwa membela Republik dan mempertahankan tanah air merupakan kewajiban agama. Seruan itu menyatukan keyakinan, keberanian, dan tanggung jawab kebangsaan; ribuan santri serta warga kemudian bergerak menjaga kemerdekaan.</p>

      <h2>Kemerdekaan yang baru seumur jagung</h2>
      <p>Pada Oktober 1945, kabar kedatangan pasukan Sekutu yang disertai NICA menyebar luas. Di berbagai daerah telah terjadi bentrokan dengan tentara Jepang dan unsur Belanda. Republik yang baru berdiri belum memiliki kekuatan militer mapan, sementara ancaman penjajahan kembali semakin nyata.</p>

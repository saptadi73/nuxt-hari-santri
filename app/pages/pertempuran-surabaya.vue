      <h2>Kalah secara militer, menang dalam makna</h2>
      <p>Pertempuran terorganisasi di dalam kota berakhir menjelang akhir November, sementara pengeboman masih berlangsung hingga awal Desember 1945. Ribuan orang gugur dan sekitar dua ratus ribu warga mengungsi dari kota yang rusak.</p>
      <p>Secara militer, Surabaya jatuh. Secara politik, pertempuran ini memiliki arti sangat besar. Belanda tidak lagi mudah menyatakan bahwa Republik hanya didukung kelompok kecil. Inggris menjadi lebih berhati-hati, sementara perhatian dan simpati internasional terhadap perjuangan kemerdekaan Indonesia semakin kuat.</p>
      <p>Pemerintah kemudian menetapkan 10 November sebagai Hari Pahlawan melalui Keputusan Presiden Nomor 316 Tahun 1959. Tugu Pahlawan berdiri di Surabaya sebagai pengingat bahwa kemerdekaan lahir dan bertahan melalui pengorbanan banyak orang.</p>


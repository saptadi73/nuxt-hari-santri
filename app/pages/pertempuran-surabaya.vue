      <p class="article-kicker">10 NOVEMBER 1945 · HARI PAHLAWAN</p>
      <p class="article-lead">Pertempuran Surabaya menjadi salah satu pertempuran paling sengit dalam Revolusi Indonesia. Selama sekitar tiga pekan, pemuda, santri, tentara Republik, dan warga mempertahankan kota menghadapi pasukan Inggris yang didukung tank, kapal perang, serta pesawat.</p>
      <p>Surabaya akhirnya dikuasai pasukan Sekutu. Namun, perlawanan itu menunjukkan kepada dunia bahwa Republik Indonesia bukan gagasan segelintir tokoh: kemerdekaan mendapat dukungan luas dan akan dipertahankan oleh rakyatnya. Warisan keberanian inilah yang dikenang setiap 10 November sebagai Hari Pahlawan.</p>

      <h2>Dari Hotel Yamato menuju kota yang bergolak</h2>
      <p>Sebulan setelah Proklamasi 17 Agustus 1945, ketegangan di Surabaya telah memuncak. Pada 19 September 1945, bendera Belanda dikibarkan di atap Hotel Yamato di Jalan Tunjungan. Bagi warga, tindakan itu dianggap merendahkan kemerdekaan yang baru saja diproklamasikan.</p>
      <p>Perundingan agar bendera diturunkan tidak mencapai kesepakatan. Sejumlah pemuda kemudian naik ke atap hotel, merobek bagian biru bendera Belanda, dan mengibarkan sisanya sebagai Merah Putih. Peristiwa itu menjadi lambang keberanian warga Surabaya mempertahankan kedaulatan.</p>
      <p>Pada 25 Oktober 1945, Brigade Infanteri ke-49 di bawah Brigadir A.W.S. Mallaby mendarat. Tugas resminya adalah melucuti tentara Jepang dan mengevakuasi tawanan, tetapi kehadiran Sekutu bersama unsur NICA menimbulkan kekhawatiran bahwa Belanda akan kembali berkuasa.</p>


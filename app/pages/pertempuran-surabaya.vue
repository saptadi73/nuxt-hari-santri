      <h2>Pertempuran pertama dan tewasnya Mallaby</h2>
      <p>Kesepakatan awal antara Gubernur R.M.T.A. Suryo dan Mallaby segera runtuh. Pembebasan tawanan Belanda dari penjara Kalisosok serta pamflet yang memerintahkan rakyat menyerahkan senjata memicu penolakan. Bentrokan meluas pada 27–30 Oktober dan sejumlah pos pasukan Inggris terkepung.</p>
      <p>Presiden Soekarno, Mohammad Hatta, dan Amir Sjarifuddin datang ke Surabaya untuk menengahi. Gencatan senjata dicapai pada 30 Oktober, tetapi sore harinya Mallaby tewas di sekitar Gedung Internatio, dekat Jembatan Merah. Penyebab pasti kematiannya tetap diperdebatkan, sementara peristiwa itu memicu kemarahan besar di pihak Inggris.</p>

      <blockquote>
        <p>Surabaya menunjukkan bahwa kemerdekaan bukan sekadar pernyataan politik, melainkan tekad bersama yang dipertahankan rakyat dengan seluruh kemampuan mereka.</p>
      </blockquote>

      <h2>Ultimatum ditolak, serangan besar dimulai</h2>
      <p>Mayor Jenderal E.C. Mansergh mengeluarkan ultimatum pada 9 November. Para pemimpin dan warga diminta menyerahkan senjata, mengibarkan bendera putih, serta melapor paling lambat pukul 06.00 keesokan harinya. Gubernur Suryo menolak ultimatum tersebut.</p>
      <p>Pada fajar 10 November, serangan besar dimulai dari darat, laut, dan udara. Pasukan Inggris memiliki keunggulan persenjataan dan organisasi. Di pihak Indonesia, tentara Republik bertempur bersama berbagai laskar dan warga dengan perlengkapan yang jauh lebih terbatas.</p>
      <p>Separuh kota dapat dikuasai dalam beberapa hari, tetapi perlawanan dari jalan ke jalan berlangsung hingga akhir November. PRI, BPRI, Tentara Pelajar, Polisi Istimewa, BBI, berbagai laskar, dan TKR bergerak dalam semangat yang sama: mempertahankan Republik.</p>

